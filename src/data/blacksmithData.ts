// Helper to calculate total bonuses from unlocked modules
export function calculateBlacksmithBonuses(unlockedIds: string[]): {
  speedReductionSec: number;
  bonusBlocksPerGather: number;
  fortuneBonusPct: number;
  bonusCoinsPerGather: number;
  critChancePct: number;
  unlockedCount: number;
} {
  let speedReductionSec = 0;
  let bonusBlocksPerGather = 0;
  let fortuneBonusPct = 0;
  let bonusCoinsPerGather = 0;
  let critChancePct = 0;

  unlockedIds.forEach(id => {
    const mod = BLACKSMITH_MODULES.find(m => m.id === id);
    if (!mod) return;

    if (mod.statType === 'speed') {
      speedReductionSec += mod.statValue;
    } else if (mod.statType === 'amount') {
      bonusBlocksPerGather += Math.round(mod.statValue);
    } else if (mod.statType === 'fortune') {
      fortuneBonusPct += Math.round(mod.statValue * 100);
    } else if (mod.statType === 'coins') {
      bonusCoinsPerGather += Math.round(mod.statValue);
    } else if (mod.statType === 'crit') {
      critChancePct += Math.round(mod.statValue * 100);
    }
  });

  return {
    speedReductionSec: Math.min(3.5, speedReductionSec), // Max reduction capped at 3.5s (minimum 1.5s interval)
    bonusBlocksPerGather,
    fortuneBonusPct,
    bonusCoinsPerGather,
    critChancePct,
    unlockedCount: unlockedIds.length
  };
}
